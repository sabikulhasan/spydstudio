/* 404 page: suggests the closest real page for a mistyped or old address. The page list is
   generated by tools/build.py; common words people type (portfolio, pricing, ugc…) map to the
   page they most likely want. Suggestions stay conservative: no guess beats a wrong guess. */
(() => {
  const box = document.querySelector('[data-nf-guess]');
  const data = document.getElementById('page-index');
  if (!box || !data) return;
  const pages = JSON.parse(data.textContent);
  const base = box.dataset.base || '/';
  let path = decodeURIComponent(location.pathname).toLowerCase();
  if (path.startsWith(base)) path = path.slice(base.length);
  path = path.replace(/\.html?$/, '').replace(/index$/, '').replace(/[^a-z0-9/]+/g, '-').replace(/^-+|-+$/g, '');
  if (!path) return;
  const aliases = {
    portfolio: 'work/', projects: 'work/', case: 'work/', examples: 'work/',
    pricing: 'services/', prices: 'services/', price: 'services/', packages: 'services/',
    ugc: 'services/ugc-content/', video: 'services/video-ads/', videos: 'services/video-ads/', ads: 'services/video-ads/',
    web: 'services/websites/', website: 'services/websites/', landing: 'services/websites/',
    deck: 'services/documents-decks/', decks: 'services/documents-decks/', profile: 'services/documents-decks/',
    marketing: 'services/marketing/', contact: 'contact/', hire: 'contact/', quote: 'contact/', about: 'about/', team: 'about/', how: 'process/',
  };
  // Levenshtein distance, normalised by the longer string: 0 = same, 1 = nothing alike.
  const dist = (a, b) => {
    const row = Array.from({ length: b.length + 1 }, (_, i) => i);
    for (let i = 1; i <= a.length; i++) {
      let prev = row[0]; row[0] = i;
      for (let j = 1; j <= b.length; j++) {
        const cur = row[j];
        row[j] = Math.min(row[j] + 1, row[j - 1] + 1, prev + (a[i - 1] === b[j - 1] ? 0 : 1));
        prev = cur;
      }
    }
    return row[b.length] / Math.max(a.length, b.length, 1);
  };
  const words = path.split(/[/-]/).filter(Boolean);
  let best = null;
  const aliased = words.map((w) => aliases[w]).find(Boolean);
  if (aliased) best = pages.find((p) => p.p === aliased);
  if (!best) {
    const last = path.split('/').filter(Boolean).pop();
    let score = 1;
    pages.forEach((p) => {
      if (!p.p) return;
      const slug = p.p.replace(/\/$/, '');
      const s = Math.min(dist(path, slug), dist(last, slug.split('/').pop()));
      if (s < score) { score = s; best = p; }
    });
    if (score > 0.45) best = null;
  }
  if (!best) return;
  const link = box.querySelector('[data-nf-link]');
  link.href = base + best.p;
  link.textContent = best.t.replace(/ · .*$/, '').replace(/^SPY-D Studio$/, 'Home');
  box.hidden = false;
})();
